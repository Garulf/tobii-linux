#[test]
fn single_strong_anchor_becomes_square_frame_box() {
    let count = anchors(INPUT_WIDTH, INPUT_HEIGHT).len();
    let mut output = vec![0.0f32; count * 9];
    let anchor = 2304 + (5 * 16 + 8) * 2;
    output[4 * count + 2 * anchor + 1] = 0.95;
    let layout = letterbox_layout(640, 480).unwrap();
    let found = detections(&output, &layout, 640, 480, &DetectOptions::default()).unwrap();
    assert_eq!(found.len(), 1);
    let face = found[0];
    assert_eq!(face.x2 - face.x1, face.y2 - face.y1);
    assert!(face.rectangle()[2] > 0);
}

/// A deterministic 64-bit LCG in [0, 1), as the vector script generated the inputs.
fn lcg(count: usize, seed: u64) -> Vec<f64> {
    let mut state = seed;
    (0..count)
        .map(|_| {
            state = state.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
            (state >> 40) as f64 / f64::from(1u32 << 24)
        })
        .collect()
}

fn synthetic(width: usize, height: usize, seed: u64) -> (Vec<u8>, Vec<f32>) {
    let frame =
        (0..height).flat_map(|y| (0..width).map(move |x| ((x * 7 + y * 3 + seed as usize) % 256) as u8)).collect();
    let count = 2820;
    let u = lcg(count * 9, seed);
    let mut output: Vec<f32> = u[..4 * count].iter().map(|v| (v - 0.5) as f32).collect();
    let mut scores: Vec<f32> = u[4 * count..6 * count].iter().map(|v| (v * 0.3) as f32).collect();
    for k in 0..(seed as usize * 2) {
        let index = 2304 + (k * 97 + seed as usize * 13) % (count - 2304);
        scores[2 * index + 1] = (0.4 + 0.05 * (k % 10) as f64) as f32;
    }
    output.extend(scores);
    output.extend(u[6 * count..].iter().map(|&v| v as f32));
    (frame, output)
}

/// The original detector 0x14007be00 in emulation (tools/face_detect_oracle.py's
/// `original`) on these synthetic frames and outputs: its letterboxed image digest and the
/// float32 bits of every returned `(x1, y1, x2, y2, score, angles)`.
#[test]
fn original_detector_vectors() {
    for (width, height, seed, region, letterbox_digest, boxes) in ORIGINAL_FACES {
        let (frame, output) = synthetic(*width, *height, *seed);
        let (image, layout) = letterbox(&frame, *width, *height).unwrap();
        assert_eq!(crate::legacy_ir::sha256_hex(&image), *letterbox_digest);
        let options = DetectOptions { region: *region, ..DetectOptions::default() };
        let found = detections(&output, &layout, *width, *height, &options).unwrap();
        let bits: Vec<[u32; 8]> = found
            .iter()
            .map(|d| [d.x1, d.y1, d.x2, d.y2, d.score, d.angles[0], d.angles[1], d.angles[2]].map(f32::to_bits))
            .collect();
        assert_eq!(bits, *boxes, "{width}x{height} seed {seed}");
    }
}

#[test]
fn face_finder_runs_the_network() {
    let Some(runtime) = runtime() else { return };
    let finder = FaceFinder::new(&runtime, &MODELS.join("ff")).unwrap();
    assert_eq!(finder.run(&[0; INPUT_WIDTH * INPUT_HEIGHT]).unwrap().len(), 25380);
    assert!(finder.detect(&[0; 640 * 480], 640, 480, &DetectOptions::default()).is_ok());
    assert!(finder.run(&[0; 10]).is_err());
}

